-- Drop old permissive policies if present
DROP POLICY IF EXISTS "Full access to companies" ON public.companies;
DROP POLICY IF EXISTS "Full access to profiles" ON public.profiles;
DROP POLICY IF EXISTS "Full access to daily_logs" ON public.daily_logs;
DROP POLICY IF EXISTS "Full access to saved_journals" ON public.saved_journals;

-- Companies: any signed-in user can read; only staff (admin, supervisor, coordinator) can write
DROP POLICY IF EXISTS "Authenticated users can read companies" ON public.companies;
CREATE POLICY "Authenticated users can read companies" ON public.companies
  FOR SELECT TO authenticated USING (true);

DROP POLICY IF EXISTS "Staff can manage companies" ON public.companies;
CREATE POLICY "Staff can manage companies" ON public.companies
  FOR ALL TO authenticated
  USING (lower(trim(coalesce(public.current_user_role(), ''))) IN ('admin', 'supervisor', 'coordinator'))
  WITH CHECK (lower(trim(coalesce(public.current_user_role(), ''))) IN ('admin', 'supervisor', 'coordinator'));

-- Profiles: users can read/update their own profile (without escalating role or self-approving); staff can read/manage directory
DROP POLICY IF EXISTS "Users read own or staff read all profiles" ON public.profiles;
CREATE POLICY "Users read own or staff read all profiles" ON public.profiles
  FOR SELECT TO authenticated
  USING (
    id = auth.uid()
    OR lower(trim(coalesce(public.current_user_role(), ''))) IN ('admin', 'supervisor', 'coordinator')
  );

DROP POLICY IF EXISTS "Users update own profile without escalating role" ON public.profiles;
CREATE POLICY "Users update own profile without escalating role" ON public.profiles
  FOR UPDATE TO authenticated
  USING (id = auth.uid())
  WITH CHECK (
    id = auth.uid()
    AND lower(trim(coalesce(role, ''))) = lower(trim(coalesce(public.current_user_role(), '')))
    AND (
      lower(trim(coalesce(public.current_user_role(), ''))) IN ('admin', 'supervisor', 'coordinator')
      OR company_status = public.current_user_company_status()
      OR company_status IN ('unassigned', 'pending')
    )
  );

DROP POLICY IF EXISTS "Staff manage profiles" ON public.profiles;
CREATE POLICY "Staff manage profiles" ON public.profiles
  FOR ALL TO authenticated
  USING (lower(trim(coalesce(public.current_user_role(), ''))) IN ('admin', 'supervisor', 'coordinator'))
  WITH CHECK (lower(trim(coalesce(public.current_user_role(), ''))) IN ('admin', 'supervisor', 'coordinator'));

-- Daily Logs: students own their logs; staff can read/manage
DROP POLICY IF EXISTS "Users manage own daily logs" ON public.daily_logs;
CREATE POLICY "Users manage own daily logs" ON public.daily_logs
  FOR ALL TO authenticated
  USING (
    user_id = auth.uid()
    OR lower(trim(coalesce(public.current_user_role(), ''))) IN ('admin', 'supervisor', 'coordinator')
  )
  WITH CHECK (
    user_id = auth.uid()
    OR lower(trim(coalesce(public.current_user_role(), ''))) IN ('admin', 'supervisor', 'coordinator')
  );

-- Saved Journals: students own their journals; staff can read/manage
DROP POLICY IF EXISTS "Users manage own saved journals" ON public.saved_journals;
CREATE POLICY "Users manage own saved journals" ON public.saved_journals
  FOR ALL TO authenticated
  USING (
    user_id = auth.uid()
    OR lower(trim(coalesce(public.current_user_role(), ''))) IN ('admin', 'supervisor', 'coordinator')
  )
  WITH CHECK (
    user_id = auth.uid()
    OR lower(trim(coalesce(public.current_user_role(), ''))) IN ('admin', 'supervisor', 'coordinator')
  );

-- Announcements: targeted students read active announcements; coordinators manage their own; admins manage all
DROP POLICY IF EXISTS "Read targeted or authored announcements" ON public.announcements;
CREATE POLICY "Read targeted or authored announcements" ON public.announcements
  FOR SELECT TO authenticated
  USING (
    lower(trim(coalesce(public.current_user_role(), ''))) = 'admin'
    OR author_id = auth.uid()
    OR (
      (expires_at IS NULL OR expires_at > now())
      AND (
        target_scope = 'all'
        OR (
          target_scope = 'department'
          AND lower(trim(coalesce(target_department, ''))) = lower(trim(coalesce(public.current_user_department(), '')))
        )
        OR (target_scope = 'company' AND target_company_id = public.current_user_company_id())
      )
    )
  );

DROP POLICY IF EXISTS "Staff insert announcements" ON public.announcements;
CREATE POLICY "Staff insert announcements" ON public.announcements
  FOR INSERT TO authenticated
  WITH CHECK (
    lower(trim(coalesce(public.current_user_role(), ''))) = 'admin'
    OR (
      lower(trim(coalesce(public.current_user_role(), ''))) IN ('supervisor', 'coordinator')
      AND author_id = auth.uid()
      AND (
        target_scope = 'all'
        OR (target_scope = 'company' AND target_company_id = public.current_user_company_id())
        OR (
          target_scope = 'department'
          AND lower(trim(coalesce(target_department, ''))) = lower(trim(coalesce(public.current_user_department(), '')))
        )
      )
    )
  );

DROP POLICY IF EXISTS "Staff update announcements" ON public.announcements;
CREATE POLICY "Staff update announcements" ON public.announcements
  FOR UPDATE TO authenticated
  USING (
    lower(trim(coalesce(public.current_user_role(), ''))) = 'admin'
    OR (
      lower(trim(coalesce(public.current_user_role(), ''))) IN ('supervisor', 'coordinator')
      AND author_id = auth.uid()
    )
  )
  WITH CHECK (
    lower(trim(coalesce(public.current_user_role(), ''))) = 'admin'
    OR (
      lower(trim(coalesce(public.current_user_role(), ''))) IN ('supervisor', 'coordinator')
      AND author_id = auth.uid()
      AND (
        target_scope = 'all'
        OR (target_scope = 'company' AND target_company_id = public.current_user_company_id())
        OR (
          target_scope = 'department'
          AND lower(trim(coalesce(target_department, ''))) = lower(trim(coalesce(public.current_user_department(), '')))
        )
      )
    )
  );

DROP POLICY IF EXISTS "Staff delete announcements" ON public.announcements;
CREATE POLICY "Staff delete announcements" ON public.announcements
  FOR DELETE TO authenticated
  USING (
    lower(trim(coalesce(public.current_user_role(), ''))) = 'admin'
    OR (
      lower(trim(coalesce(public.current_user_role(), ''))) IN ('supervisor', 'coordinator')
      AND author_id = auth.uid()
    )
  );

-- Announcement Reads: each user tracks their own read receipts
DROP POLICY IF EXISTS "Users manage own announcement reads" ON public.announcement_reads;
CREATE POLICY "Users manage own announcement reads" ON public.announcement_reads
  FOR ALL TO authenticated
  USING (user_id = auth.uid())
  WITH CHECK (user_id = auth.uid());

-- Enable Realtime notifications for announcements
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_publication_tables
    WHERE pubname = 'supabase_realtime'
      AND schemaname = 'public'
      AND tablename = 'announcements'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.announcements;
  END IF;
END $$;

