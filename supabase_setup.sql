-- ==============================================================================
-- InternTrack Complete Supabase Database Setup Script
-- Run this in your Supabase SQL Editor (Dashboard > SQL Editor > New query)
-- ==============================================================================

-- 1. Enable Required Extensions
CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- 2. Create Companies Table
CREATE TABLE IF NOT EXISTS public.companies (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  address TEXT,
  capacity INTEGER DEFAULT 0,
  required_hours INTEGER DEFAULT 0,
  department TEXT,
  logo_url TEXT,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. Create Profiles Table (links to Supabase auth.users)
CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  first_name TEXT,
  last_name TEXT,
  username TEXT,
  department TEXT,
  role TEXT DEFAULT 'student', -- 'student', 'supervisor', 'admin'
  company_id BIGINT REFERENCES public.companies(id) ON DELETE SET NULL,
  company_status TEXT DEFAULT 'unassigned', -- 'unassigned', 'pending', 'active'
  avatar_url TEXT,
  raw_password TEXT,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 4. Create Daily Logs Table
CREATE TABLE IF NOT EXISTS public.daily_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
  date TEXT,
  start_shift TEXT,
  end_shift TEXT,
  category TEXT,
  hours TEXT,
  description TEXT,
  learnings TEXT,
  proof_url TEXT,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 5. Create Saved Journals Table
CREATE TABLE IF NOT EXISTS public.saved_journals (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
  week_number TEXT,
  inclusive_dates TEXT,
  file_name TEXT,
  file_path TEXT,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- ==============================================================================
-- 6. Row Level Security (RLS) Policies
-- Enables RLS while allowing full access for InternTrack features
-- ==============================================================================

ALTER TABLE public.companies ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.daily_logs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.saved_journals ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Full access to companies" ON public.companies;
CREATE POLICY "Full access to companies" ON public.companies 
  FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Full access to profiles" ON public.profiles;
CREATE POLICY "Full access to profiles" ON public.profiles 
  FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Full access to daily_logs" ON public.daily_logs;
CREATE POLICY "Full access to daily_logs" ON public.daily_logs 
  FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Full access to saved_journals" ON public.saved_journals;
CREATE POLICY "Full access to saved_journals" ON public.saved_journals 
  FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

-- ==============================================================================
-- 7. Storage Buckets (avatars, journals, logpicture)
-- ==============================================================================

INSERT INTO storage.buckets (id, name, public)
VALUES 
  ('avatars', 'avatars', true),
  ('journals', 'journals', true),
  ('logpicture', 'logpicture', true)
ON CONFLICT (id) DO UPDATE SET public = true;

-- Storage RLS Policies
DROP POLICY IF EXISTS "Public access to avatars" ON storage.objects;
CREATE POLICY "Public access to avatars" ON storage.objects
  FOR ALL TO anon, authenticated
  USING (bucket_id = 'avatars')
  WITH CHECK (bucket_id = 'avatars');

DROP POLICY IF EXISTS "Public access to journals" ON storage.objects;
CREATE POLICY "Public access to journals" ON storage.objects
  FOR ALL TO anon, authenticated
  USING (bucket_id = 'journals')
  WITH CHECK (bucket_id = 'journals');

DROP POLICY IF EXISTS "Public access to logpicture" ON storage.objects;
CREATE POLICY "Public access to logpicture" ON storage.objects
  FOR ALL TO anon, authenticated
  USING (bucket_id = 'logpicture')
  WITH CHECK (bucket_id = 'logpicture');

